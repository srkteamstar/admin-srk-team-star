/*
 * Builds the static directory Vercel serves through its CDN.
 *
 * Vercel ignores express.static(), while this repository intentionally keeps
 * authored browser files split across frontend/assets, frontend/js and
 * frontend/public. Copy those three trees into a generated root public/
 * directory during deployment, minifying only the generated JS/CSS copies.
 * HTML stays out of the CDN and is served by the Express adapter so the
 * application's per-document CSP remains intact.
 */
const fs = require('fs');
const path = require('path');
const { transformSync } = require('esbuild');

const MARKER_NAME = '.generated-by-build-vercel-public';
const copies = [
    ['frontend/assets', 'assets'],
    ['frontend/js', 'js'],
    ['frontend/public', '.']
];

function buildPublic(projectDirectory = path.resolve(__dirname, '..')) {
    const projectRoot = path.resolve(projectDirectory);
    const outputRoot = path.resolve(projectRoot, 'public');
    const marker = path.join(outputRoot, MARKER_NAME);

    if (outputRoot !== path.join(projectRoot, 'public')) {
        throw new Error(`Refusing to build outside the expected public directory: ${outputRoot}`);
    }

    // Validate all inputs before replacing a previous build.
    for (const [sourceRelative] of copies) {
        if (!fs.existsSync(path.join(projectRoot, sourceRelative))) {
            throw new Error(`Missing Vercel static source: ${sourceRelative}`);
        }
    }

    if (fs.existsSync(outputRoot)) {
        if (fs.lstatSync(outputRoot).isSymbolicLink() || !fs.existsSync(marker)) {
            throw new Error('Refusing to replace public/: it was not created by the Vercel build adapter.');
        }
        fs.rmSync(outputRoot, { recursive: true, force: true });
    }

    fs.mkdirSync(outputRoot, { recursive: true });
    // Mark ownership immediately so a failed transform can be rebuilt safely.
    fs.writeFileSync(marker, 'Generated by tools/build-vercel-public.js. Do not edit.\n');

    for (const [sourceRelative, destinationRelative] of copies) {
        const source = path.join(projectRoot, sourceRelative);
        const destination = path.resolve(outputRoot, destinationRelative);

        if (destination !== outputRoot && !destination.startsWith(outputRoot + path.sep)) {
            throw new Error(`Refusing to copy outside public/: ${destination}`);
        }

        fs.cpSync(source, destination, { recursive: true, force: true });
    }

    const stats = {
        files: 0,
        bytes: 0,
        js: { files: 0, before: 0, after: 0 },
        css: { files: 0, before: 0, after: 0 }
    };

    const optimize = (dir) => {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            const full = path.join(dir, entry.name);
            if (entry.isDirectory()) {
                optimize(full);
                continue;
            }
            // Never write through a copied symlink into an authored source.
            if (!entry.isFile()) continue;

            const extension = path.extname(entry.name).toLowerCase();
            if (extension === '.js' || extension === '.css') {
                const loader = extension.slice(1);
                const source = fs.readFileSync(full, 'utf8');
                const { code } = transformSync(source, {
                    loader,
                    minify: true,
                    charset: 'utf8',
                    legalComments: 'inline',
                    sourcefile: path.relative(outputRoot, full),
                    // No bundle, format, property mangling or tree shaking:
                    // classic scripts share their top-level names and expose
                    // window.* handlers to other scripts and inline markup.
                    treeShaking: false,
                    target: loader === 'js'
                        ? 'es2020'
                        : ['chrome90', 'edge90', 'firefox90', 'safari14']
                });
                const before = Buffer.byteLength(source);
                const after = Buffer.byteLength(code);
                // An already-minified vendor file may not get smaller.
                if (after < before) fs.writeFileSync(full, code);
                stats[loader].files += 1;
                stats[loader].before += before;
                stats[loader].after += Math.min(before, after);
            }
            stats.files += 1;
            stats.bytes += fs.statSync(full).size;
        }
    };
    optimize(outputRoot);
    return stats;
}

if (require.main === module) {
    const stats = buildPublic();
    console.log(`Vercel public output: ${stats.files} files, ${(stats.bytes / 1024 / 1024).toFixed(2)} MB.`);
    for (const type of ['js', 'css']) {
        const { files, before, after } = stats[type];
        console.log(`${type.toUpperCase()}: ${files} files, ${(before / 1024).toFixed(1)} → ${(after / 1024).toFixed(1)} KiB.`);
    }
}

module.exports = { buildPublic };
